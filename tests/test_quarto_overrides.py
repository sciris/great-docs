"""Tests for the raw `_quarto.yml` passthrough (`quarto:` and `_quarto.user.yml`)"""

from pathlib import Path

import pytest
from yaml12 import read_yaml

from great_docs import Config, GreatDocs
from great_docs._utils import merge_quarto_overrides, write_quarto_yml


def test_merge_quarto_overrides_rules():
    config = {
        "format": {"html": {"theme": "flatly", "toc": True, "css": ["a.css"]}},
        "website": {"title": "Pkg"},
    }
    overrides = {
        "format": {"html": {"theme": {"light": ["flatly", "custom.scss"]}, "toc": None, "css": ["b.css"]}},
        "execute": {"freeze": "auto"},
    }
    result = merge_quarto_overrides(config, overrides)

    assert result == {
        "format": {"html": {"theme": {"light": ["flatly", "custom.scss"]}, "css": ["b.css"]}},
        "website": {"title": "Pkg"},
        "execute": {"freeze": "auto"},
    }
    assert config["format"]["html"]["toc"] is True  # not mutated


def _make_docs(tmp_path: Path, gd_yml: str) -> GreatDocs:
    (tmp_path / "pyproject.toml").write_text('[project]\nname = "mypkg"\n', encoding="utf-8")
    (tmp_path / "great-docs.yml").write_text(gd_yml, encoding="utf-8")
    docs = GreatDocs(project_path=str(tmp_path))
    docs._config = Config(tmp_path)
    docs.build_dir.mkdir(parents=True, exist_ok=True)
    generated = {
        "project": {"type": "website"},
        "website": {"title": "mypkg", "page-footer": {"left": "GD"}},
        "format": {"html": {"theme": "flatly", "toc-depth": 2}},
    }
    write_quarto_yml(docs.build_dir / "_quarto.yml", generated)
    return docs


def _read(docs: GreatDocs) -> dict:
    with open(docs.build_dir / "_quarto.yml", encoding="utf-8") as f:
        return read_yaml(f)


def test_quarto_block_merges_into_generated_config(tmp_path):
    docs = _make_docs(
        tmp_path,
        "quarto:\n"
        "  format:\n"
        "    html:\n"
        "      theme:\n"
        "        light: [flatly, custom.scss]\n"
        "        dark: [darkly, custom.scss]\n"
        "      mainfont: Source Sans Pro\n"
        "  website:\n"
        "    page-footer: null\n",
    )

    assert docs._apply_quarto_overrides() == ["great-docs.yml `quarto`"]
    result = _read(docs)
    assert result["format"]["html"] == {
        "theme": {"light": ["flatly", "custom.scss"], "dark": ["darkly", "custom.scss"]},
        "toc-depth": 2,
        "mainfont": "Source Sans Pro",
    }
    assert result["website"] == {"title": "mypkg"}
    assert (docs.build_dir / "_quarto.yml").read_text().startswith("# Generated by Great Docs")


def test_user_overlay_file_merges_last(tmp_path):
    docs = _make_docs(tmp_path, "quarto:\n  format:\n    html:\n      toc-depth: 3\n")
    (tmp_path / "_quarto.user.yml").write_text(
        "format:\n  html:\n    toc-depth: 4\nwebsite:\n  title: Custom\n", encoding="utf-8"
    )

    assert docs._apply_quarto_overrides() == ["great-docs.yml `quarto`", "_quarto.user.yml"]
    result = _read(docs)
    assert result["format"]["html"]["toc-depth"] == 4
    assert result["website"]["title"] == "Custom"


def test_no_overrides_leaves_file_untouched(tmp_path):
    docs = _make_docs(tmp_path, "display_name: Pkg\n")
    before = (docs.build_dir / "_quarto.yml").read_text()

    assert docs._apply_quarto_overrides() == []
    assert (docs.build_dir / "_quarto.yml").read_text() == before


def test_quarto_block_must_be_mapping(tmp_path):
    docs = _make_docs(tmp_path, "quarto: [not, a, mapping]\n")
    with pytest.raises(ValueError, match="must be a mapping"):
        docs._apply_quarto_overrides()


def test_user_overlay_file_must_be_mapping(tmp_path):
    docs = _make_docs(tmp_path, "")
    (tmp_path / "_quarto.user.yml").write_text("- a\n- b\n", encoding="utf-8")
    with pytest.raises(ValueError, match="must contain a mapping"):
        docs._apply_quarto_overrides()
